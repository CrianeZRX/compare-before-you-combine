#!/usr/bin/env python3
"""Figure, supplementary tables and derived numbers of the 33-19 experiments.

Usage: python3 scripts/make_s19.py            (run from anywhere)
Inputs : data33_19/S19_E1.json, S19_E2.json, S19_E3.json, S19_PREDICT.json
Outputs: figures/fig_ratio.pdf
         tables/supp_s19_scores.tex, supp_s19_native.tex, supp_s19_bins.tex,
         supp_s19_ratio.tex, supp_s19_reject.tex
         data33_19/derived_s19.json  (numbers computed here and quoted in the text)
"""
import json, os, hashlib
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(ROOT, "data33_19")
F = os.path.join(ROOT, "figures")
T = os.path.join(ROOT, "tables")
COLW = min(float(os.environ.get("FIGW", 5.45)), 3.45)  # one column of the 5p layout

C = dict(blue="#0072B2", orange="#E69F00", green="#009E73", red="#D55E00",
         purple="#CC79A7", sky="#56B4E9", grey="#7F7F7F", black="#222222")
plt.rcParams.update({
    "font.size": 8, "axes.titlesize": 8.5, "axes.labelsize": 8, "legend.fontsize": 7,
    "xtick.labelsize": 7.5, "ytick.labelsize": 7.5, "axes.spines.top": False,
    "axes.spines.right": False, "axes.linewidth": 0.6, "lines.linewidth": 1.3,
    "pdf.fonttype": 42, "font.family": "DejaVu Sans", "legend.frameon": False,
})
DS = [("lmo", "LM-O"), ("tless", "T-LESS"), ("tudl", "TUD-L"), ("icbin", "IC-BIN"), ("ycbv", "YCB-V")]
derived = {"inputs": {}}


def load(name):
    p = os.path.join(D, name)
    derived["inputs"][name] = hashlib.sha256(open(p, "rb").read()).hexdigest()
    return json.load(open(p, encoding="utf8"))


def panel(ax, s):
    ax.text(-0.02, 1.04, s, transform=ax.transAxes, fontsize=9, fontweight="bold", va="bottom", ha="right")


def wtab(name, text):
    os.makedirs(T, exist_ok=True)
    open(os.path.join(T, name), "w").write(text)


e1, e2, e3 = load("S19_E1.json"), load("S19_E2.json"), load("S19_E3.json")

# ---------------------------------------------------------------- E1: scores on fixed poses
SC = [("FPraw", "FoundationPose, per-call"), ("FPsingle", "FoundationPose, alone"), ("FPjoint", "FoundationPose, joint"),
      ("MPsingle", "MegaPose, alone"), ("MPjoint", "MegaPose, joint"), ("Depth", "Depth consistency"),
      ("MaskIoU", "Rendered-mask IoU"), ("Chamfer", "Truncated chamfer")]
rec = e1["E1b_E1d"]["records"]
ar = e1["AR"]
rows = []
d1 = {}
for k, lab in SC:
    acc = [100 * rec[d]["cross_call"][k]["ties_half_accuracy"] for d, _ in DS]
    p = rec["pooled"]["cross_call"][k]
    lo, hi = (100 * x for x in p["ties_half_ci95"])
    a = ar["equal_weight_mean"][k]["estimate_pp"]["ar"]
    d1[k] = {"pooled": 100 * p["ties_half_accuracy"], "ci": [lo, hi], "wins": p["strict_wins"], "pairs": p["total_pairs"],
             "ar": a, "by_dataset": dict(zip([d for d, _ in DS], acc))}
    rows.append(f"{lab} & " + " & ".join(f"{v:.2f}" for v in acc) + f" & {100 * p['ties_half_accuracy']:.2f} [{lo:.2f}, {hi:.2f}] & {a:.2f} \\\\")
ss = rec["pooled"]["set_sensitivity"]
d1["set_sensitivity"] = {k: v["delta_divided_by_IQR"] for k, v in ss.items()}
n_pairs = rec["pooled"]["cross_call"]["FPraw"]["total_pairs"]
d1["pairs"] = n_pairs
wtab("supp_s19_scores.tex",
     "% generated by scripts/make_s19.py from data33_19/S19_E1.json; do not edit\n"
     "\\begin{tabular}{@{}lrrrrrrr@{}}\n\\toprule\n"
     "Score & LM-O & T-LESS & TUD-L & IC-BIN & YCB-V & Pooled [95\\% CI] & AR \\\\\n\\midrule\n"
     + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")

# set sensitivity row block (pooled)
ssrows = []
for k, lab in [("FoundationPose", "FoundationPose"), ("MegaPose", "MegaPose"), ("Depth", "Depth consistency"),
               ("MaskIoU", "Rendered-mask IoU"), ("Chamfer", "Truncated chamfer")]:
    v = ss[k]["delta_divided_by_IQR"]
    ssrows.append(f"{lab} & {v['median']:.3f} & {v['p90']:.3f} & {v['max']:.3f} \\\\")
wtab("supp_s19_setsens.tex",
     "% generated by scripts/make_s19.py from data33_19/S19_E1.json; do not edit\n"
     "\\begin{tabular}{@{}lrrr@{}}\n\\toprule\nScore & Median & P90 & Max \\\\\n\\midrule\n"
     + "\n".join(ssrows) + "\n\\bottomrule\n\\end{tabular}\n")

# native scores of other pipelines
nat = e1["E1c"]["methods"]
nrows, dn = [], {}
for m, lab in [("gigapose", "GigaPose"), ("sam6d", "SAM-6D (PEM)")]:
    cells = []
    for d in ("lmo", "icbin", "pooled"):
        cc = nat[m][d]["cross_call"]
        cells.append(f"{100 * cc['ties_half_accuracy']:.2f} ({cc['total_pairs']:,})" if isinstance(cc, dict) and "total_pairs" in cc else f"{100 * cc['ties_half_accuracy']:.2f}")
    p = nat[m]["pooled"]["cross_call"]
    lo, hi = (100 * x for x in p["ties_half_ci95"])
    w = nat[m]["pooled"].get("within_call")
    wtxt = f"{100 * w['ties_half_accuracy']:.2f}" if isinstance(w, dict) else "--"
    dn[m] = {"pooled": 100 * p["ties_half_accuracy"], "ci": [lo, hi], "pairs": p["total_pairs"],
             "within": 100 * w["ties_half_accuracy"] if isinstance(w, dict) else None}
    nrows.append(f"{lab} & {cells[0]} & {cells[1]} & {cells[2]} [{lo:.2f}, {hi:.2f}] & {wtxt} \\\\")
d1["native"] = dn
wtab("supp_s19_native.tex",
     "% generated by scripts/make_s19.py from data33_19/S19_E1.json; do not edit\n"
     "\\begin{tabular}{@{}lrrrr@{}}\n\\toprule\n"
     "Pipeline & LM-O (pairs) & IC-BIN (pairs) & Pooled (pairs) [95\\% CI] & Within call \\\\\n\\midrule\n"
     + "\n".join(nrows) + "\n\\bottomrule\n\\end{tabular}\n")

# bins
bins = e1["E1e"]["records"]
brows, db = [], {}
for d, lab in [("xyzibd", "XYZ-IBD"), ("ipd", "IPD")]:
    db[d] = {}
    for pool in ("B1", "B3"):
        cc, wc = bins[d][pool]["cross_call"], bins[d][pool]["within_call"]
        lo, hi = (100 * x for x in cc["ties_half_ci95"])
        db[d][pool] = {"cross": 100 * cc["ties_half_accuracy"], "ci": [lo, hi], "pairs": cc["total_pairs"], "within": 100 * wc["ties_half_accuracy"]}
        brows.append(f"{lab} & {pool} & {cc['total_pairs']:,} & {100 * cc['ties_half_accuracy']:.2f} [{lo:.2f}, {hi:.2f}] & {100 * wc['ties_half_accuracy']:.2f} \\\\")
d1["bins"] = db
wtab("supp_s19_bins.tex",
     "% generated by scripts/make_s19.py from data33_19/S19_E1.json; do not edit\n"
     "\\begin{tabular}{@{}llrrr@{}}\n\\toprule\n"
     "Dataset & Pool & Cross-call pairs & Cross call [95\\% CI] & Within call \\\\\n\\midrule\n"
     + "\n".join(brows) + "\n\\bottomrule\n\\end{tabular}\n")
derived["E1"] = d1

# ---------------------------------------------------------------- E2: count ratio
FALSE = ("pose", "identity", "background", "duplicate")
conds = []
for exp in ("E2a", "E2b"):
    for d, res in e2[exp].items():
        for tau, t in res["threshold_results"].items():
            comp = t["output_composition"]
            dtp = comp["B4"]["TP"] - comp["B1"]["TP"]
            dfp = sum(comp["B4"][k] for k in FALSE) - sum(comp["B1"][k] for k in FALSE)
            cond = t["offline_2D_condition"] if "offline_2D_condition" in t else None
            conds.append(dict(exp=exp, ds=d, tau=float(tau),
                              ratio=(cond or {}).get("median_count_ratio"),
                              below1=(cond or {}).get("fraction_ratio_below_one"),
                              b1=t["AP"]["B1"]["estimate_pp"]["ap"], b4=t["AP"]["B4"]["estimate_pp"]["ap"],
                              delta=t["B4_minus_B1"]["estimate_pp"], ci=t["B4_minus_B1"]["ci95_pp"],
                              added_correct=dtp, added_false=dfp,
                              false_per_correct=(dfp / dtp) if dtp > 0 else None))
# E2b conditions are stored in the condition block
for c in conds:
    if c["ratio"] is None:
        r = e2["condition_source"]["E2b"]["realized"]["all_five"][c["ds"]]
        c["ratio"], c["below1"] = r["median_count_ratio"], r["fraction_ratio_below_one"]
NAME = {"xyzibd": "XYZ-IBD", "ipd": "IPD", "icbin": "IC-BIN", "tudl": "TUD-L"}
order = sorted(conds, key=lambda c: ({"xyzibd": 0, "ipd": 1, "icbin": 2, "tudl": 3}[c["ds"]], c["tau"]))
rrows = []
groups = []
for c in order:  # thresholds that accept the same detections give identical rows; report them once
    if groups and groups[-1][0]["ds"] == c["ds"] and abs(groups[-1][0]["ratio"] - c["ratio"]) < 1e-9 and abs(groups[-1][0]["delta"] - c["delta"]) < 1e-9:
        groups[-1].append(c)
    else:
        groups.append([c])
for g in groups:
    c = g[0]
    taus = f"{g[0]['tau']:.3f}" if len(g) == 1 else f"{g[0]['tau']:.3f}--{g[-1]['tau']:.3f}"
    fpc = f"{c['false_per_correct']:.1f}" if c["false_per_correct"] is not None else "--"
    rrows.append(f"{NAME[c['ds']]} & {taus} & {c['ratio']:.2f} & {100 * c['below1']:.0f} & {c['b1']:.2f} & {c['b4']:.2f} & "
                 f"{c['delta']:+.2f} [{c['ci'][0]:+.2f}, {c['ci'][1]:+.2f}] & {c['added_correct']:+d} & {c['added_false']:+d} & {fpc} \\\\")
wtab("supp_s19_ratio.tex",
     "% generated by scripts/make_s19.py from data33_19/S19_E2.json; do not edit\n"
     "\\begin{tabular}{@{}lrrrrrrrrr@{}}\n\\toprule\n"
     "Dataset & $\\tau$ & Ratio & $<1$ (\\%) & \\rowB{1} & \\rowB{4} & \\rowB{4}$-$\\rowB{1} [95\\% CI] & $\\Delta$correct & $\\Delta$false & False/correct \\\\\n\\midrule\n"
     + "\n".join(rrows) + "\n\\bottomrule\n\\end{tabular}\n")
five = e2["condition_source"]["E2b"]["realized"]["all_five"]
derived["E2"] = {"conditions": order,
                 "classic_median_ratios": {k: v["median_count_ratio"] for k, v in five.items()}}

# figure: B4 - B1 against the count ratio (a, preregistered) and the false poses per correct one (b, post hoc)
fig, (a, b) = plt.subplots(2, 1, figsize=(COLW, 3.55), gridspec_kw=dict(hspace=0.62))
style = {"xyzibd": (C["blue"], "o"), "ipd": (C["orange"], "s"), "icbin": (C["purple"], "D"), "tudl": (C["green"], "^")}
seen = set()
for ax, key in ((a, "ratio"), (b, "false_per_correct")):
    for d in ("xyzibd", "ipd", "icbin", "tudl"):
        pts = [c for c in order if c["ds"] == d]
        uniq = {}
        for c in pts:  # equal conditions (identical accepted sets) are drawn once
            uniq[(round(c["ratio"], 4), round(c["delta"], 4))] = c
        pts = sorted(uniq.values(), key=lambda c: c["ratio"])
        xs = [c[key] if c[key] is not None else 60.0 for c in pts]
        ys = [c["delta"] for c in pts]
        err = np.array([[c["delta"] - c["ci"][0] for c in pts], [c["ci"][1] - c["delta"] for c in pts]])
        col, mk = style[d]
        ax.errorbar(xs, ys, yerr=err, color=col, marker=mk, ms=4, lw=1.0, capsize=2, elinewidth=0.8,
                    label=NAME[d] if d not in seen else None)
        seen.add(d)
    ax.axhline(0, color=C["black"], lw=0.7)
    ax.set_xscale("log"); ax.minorticks_off()
    ax.set_ylabel("$B4-B1$ (AP points)"); ax.set_ylim(-8.5, 10.5)
a.axvline(1, color=C["grey"], lw=0.7, ls=(0, (3, 2)))
a.set_xticks([0.5, 1, 2, 4, 11]); a.set_xticklabels(["0.5", "1", "2", "4", "11"])
a.set_xlabel("Median count ratio (detections per instance)")
a.legend(loc="upper right", ncol=2, handlelength=1.4, columnspacing=0.9)
panel(a, "(a)")
b.set_xticks([5, 10, 20, 40, 60]); b.set_xticklabels(["5", "10", "20", "40", "none\ncorrect"])
b.set_xlabel("Added false poses per added correct pose (post hoc)")
panel(b, "(b)")
os.makedirs(F, exist_ok=True)
fig.savefig(os.path.join(F, "fig_ratio.pdf"), bbox_inches="tight", pad_inches=0.02); plt.close(fig)

# ---------------------------------------------------------------- E3: rejection step
jrows, d3 = [], {}
for d in ("xyzibd", "ipd"):
    r = e3["datasets"][d]
    ap = {k: r["AP"][k]["estimate_pp"]["ap"] for k in ("B1", "B4", "B4reject")}
    dd = r["B4rej_minus_B1"]
    d3[d] = {"ap": ap, "delta": dd["estimate_pp"], "ci": dd["ci95_pp"], "retained": r["B4_gain_retained"]}
    jrows.append(f"{NAME[d]} & {ap['B1']:.2f} & {ap['B4']:.2f} & {ap['B4reject']:.2f} & {dd['estimate_pp']:+.2f} [{dd['ci95_pp'][0]:+.2f}, {dd['ci95_pp'][1]:+.2f}] & {100 * r['B4_gain_retained']:.1f} \\\\")
wtab("supp_s19_reject.tex",
     "% generated by scripts/make_s19.py from data33_19/S19_E3.json; do not edit\n"
     "\\begin{tabular}{@{}lrrrrr@{}}\n\\toprule\n"
     "Dataset & \\rowB{1} & \\rowB{4} & \\rowB{4} + rejection & Rejection $-$ \\rowB{1} [95\\% CI] & Effect retained (\\%) \\\\\n\\midrule\n"
     + "\n".join(jrows) + "\n\\bottomrule\n\\end{tabular}\n")
derived["E3"] = d3

json.dump(derived, open(os.path.join(D, "derived_s19.json"), "w"), indent=1, default=float)
print("ok", {k: round(v["pooled"], 2) for k, v in d1.items() if isinstance(v, dict) and "pooled" in v})
