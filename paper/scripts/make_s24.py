#!/usr/bin/env python3
"""Tables and derived numbers from the 33-24 replay on the WAPR poses (data33_24/).

Usage:  python scripts/make_s24.py          (run from the manuscript root)
Inputs: data33_24/S24_RULES.json   rules for the WAPR replay, written before any of its results
        data33_24/S24_B_wapr.json  k-frame replay of the released check (compare6d.check, ties half), WAPR poses
        data33_24/S24_A_wapr.json  the same check on all 750 frames
        (replay.py in the same folder produced both from outputs/r33_22/S22_E4.json)
        data33_24/S24_RULES_SERVER.json, S24_B_FP.json, S24_C.json, S24_A_rest.json, REPORT33_24.md
                                   server deliverables of instruction 33-24 v1.1 (same tool, same sampling):
                                   replay on the best poses of FoundationPose, paired AP differences, tie re-check
Outputs:
  (tables/tab_sign.tex moved to make_s25.py, which replays the released check with its six-image rule)
  tables/supp_s24_replay.tex       lowest share of correct readings over the five datasets, WAPR poses
  tables/supp_s24_replay_fp.tex    the same on the best poses of FoundationPose (seven scores)
  tables/supp_s24_apdiff.tex       paired AP differences of the main contrasts with image and scene intervals
  data33_24/derived_s24.json       numbers quoted in the text
"""
import json, os, hashlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(ROOT, "data33_24"); T = os.path.join(ROOT, "tables")
sha = lambda p: hashlib.sha256(open(p, "rb").read()).hexdigest()

rules = json.load(open(os.path.join(D, "S24_RULES.json")))
B = json.load(open(os.path.join(D, "S24_B_wapr.json")))
A = json.load(open(os.path.join(D, "S24_A_wapr.json")))
assert B["rules_sha256"] == sha(os.path.join(D, "S24_RULES.json")), "replay was not run under these rules"
R = B["results"]
DS = rules["datasets"]
KS = [str(k) for k in rules["k"]]
REV = rules["scores"]["expected_reversed"]
COMP = rules["scores"]["expected_comparable"]
ORDER = REV + COMP
LABEL = {"fp_single": "FP alone", "wbps_neg": "WBPS reversed", "wbps_raw": "WBPS",
         "wbps_single": "WBPS alone", "depth": "Depth cons.", "fp_joint": "FP joint"}


def low(score, k, key="correct"):
    return min(R[score][ds][k][key] for ds in DS)


def high(score, k, key):
    return max(R[score][ds][k][key] for ds in DS)


lines = ["% generated by scripts/make_s24.py from data33_24 -- do not edit by hand",
         "\\setlength{\\tabcolsep}{4pt}",
         "\\begin{tabular}{@{}c cc cccc cc@{}}", "\\toprule",
         " & \\multicolumn{2}{c}{Should read reversed} & \\multicolumn{4}{c}{Should read comparable} & \\multicolumn{2}{c}{Any score} \\\\",
         "\\cmidrule(lr){2-3}\\cmidrule(lr){4-7}\\cmidrule(l){8-9}",
         "$k$ & " + " & ".join(LABEL[s] for s in ORDER) + " & Wrong & No pairs \\\\", "\\midrule"]
derived = {"k": {}}
for k in KS:
    wrong = max(high(s, k, "wrong") for s in ORDER)
    nop = max(high(s, k, "no_pairs") for s in ORDER)
    cells = [f"{low(s, k):.1f}" for s in ORDER]
    lines.append(f"{k} & " + " & ".join(cells) + f" & {wrong:.1f} & {nop:.1f} \\\\")
    derived["k"][k] = {"lowest_correct": {s: low(s, k) for s in ORDER},
                       "highest_wrong": wrong, "highest_no_pairs": nop,
                       "lowest_correct_reversed": min(low(s, k) for s in REV),
                       "lowest_correct_comparable": min(low(s, k) for s in COMP)}
lines += ["\\bottomrule", "\\end{tabular}"]
open(os.path.join(T, "supp_s24_replay.tex"), "w").write("\n".join(lines) + "\n")

# readings fixed in advance
derived["RB1_fp_single_k10_all_ge90"] = all(R["fp_single"][ds]["10"]["correct"] >= 90 for ds in DS)
derived["RB2_k10_wrong_le1"] = all(R[s][ds]["10"]["wrong"] <= 1 for s in ORDER for ds in DS)
derived["RB3_min_k"] = {s: {ds: next((k for k in KS if R[s][ds][k]["correct"] >= 90), ">20") for ds in DS} for s in ORDER}
derived["k10_all_correct_100"] = all(R[s][ds]["10"]["correct"] == 100 for s in ORDER for ds in DS)
derived["k3_lowest_correct_except_depth"] = min(low(s, "3") for s in ORDER if s != "depth")
derived["k3_lowest_correct_depth"] = low("depth", "3")
derived["pairs_median_k10"] = {s: {ds: R[s][ds]["10"]["pairs_median"] for ds in DS} for s in ["fp_single"]}
derived["full_sample"] = {s: {"pairs": A[s]["pooled"]["pairs"], "ties": A[s]["pooled"]["ties"],
                              "accuracy_pp": 100 * A[s]["pooled"]["accuracy"],
                              "interval_pp": [100 * x for x in A[s]["pooled"]["interval_95"]],
                              "reading": A[s]["pooled"]["reading"],
                              "readings_by_dataset": {ds: A[s][ds]["reading"] for ds in DS}} for s in ORDER}
derived["inputs"] = {f"data33_24/{n}": sha(os.path.join(D, n)) for n in
                     ["S24_RULES.json", "S24_B_wapr.json", "S24_A_wapr.json", "replay.py"]}
# ---------------- server: replay on the best poses of FoundationPose ----------------
BF = json.load(open(os.path.join(D, "S24_B_FP.json")))
CL = ["lmo", "tless", "tudl", "icbin", "ycbv"]
bd = BF["by_dataset"]
assert BF["tool"]["sha256"] == rules["tool"]["sha256"], "server used another check.py"
FPS = ["fp_raw", "fp_single", "fp_joint", "megapose_single", "depth", "mask_iou", "chamfer"]
FPL = {"fp_raw": "FP per call", "fp_single": "FP alone", "fp_joint": "FP joint", "megapose_single": "MegaPose",
       "depth": "Depth cons.", "mask_iou": "Mask IoU", "chamfer": "Chamfer"}
for s_ in FPS:
    for d_ in CL:
        assert BF["expectations"][d_][s_] == ("reversed" if s_ in ("fp_raw", "fp_single") else "comparable")
main = ["% generated by scripts/make_s24.py from data33_24 -- do not edit by hand",
        "\\setlength{\\tabcolsep}{5pt}",
        "\\begin{tabular}{@{}c >{\\centering\\arraybackslash}p{2.2cm} >{\\centering\\arraybackslash}p{1.95cm} >{\\centering\\arraybackslash}p{1.5cm}@{}}",
        "\\toprule",
        "Frames $k$ & Lowest share, five datasets & Datasets at 100\\% & XYZ-IBD \\\\", "\\midrule"]
fpd = {}
for k in KS:
    cls = [bd[d_]["fp_raw"][k]["correct"] for d_ in CL]
    x = bd["xyzibd"]["fp_raw"][k]
    main.append(f"{k} & {min(cls):.1f}\\% & {sum(v == 100 for v in cls)} of 5 & {x['correct']:.1f}\\% \\\\")
    fpd[k] = {"classic_lowest": min(cls), "classic_at_100": sum(v == 100 for v in cls), "xyz_correct": x["correct"],
              "xyz_no_pairs": x["no_pairs"], "xyz_insufficient": x["insufficient"],
              "lowest_correct": {s_: min(bd[d_][s_][k]["correct"] for d_ in CL) for s_ in FPS},
              "highest_wrong": max(bd[d_][s_][k]["wrong"] for d_ in bd for s_ in bd[d_]),
              "highest_no_pairs_classic": max(bd[d_][s_][k]["no_pairs"] for d_ in CL for s_ in FPS),
              "xyz_depth_correct": bd["xyzibd"]["depth"][k]["correct"]}
main += ["\\bottomrule", "\\end{tabular}"]
# tables/tab_sign.tex is now written by make_s25.py (the released check with its six-image rule)
sup = ["% generated by scripts/make_s24.py from data33_24 -- do not edit by hand",
       "\\setlength{\\tabcolsep}{4pt}",
       "\\begin{tabular}{@{}c cc ccccc cc@{}}", "\\toprule",
       " & \\multicolumn{2}{c}{Should read reversed} & \\multicolumn{5}{c}{Should read comparable} & \\multicolumn{2}{c}{Any score} \\\\",
       "\\cmidrule(lr){2-3}\\cmidrule(lr){4-8}\\cmidrule(l){9-10}",
       "$k$ & " + " & ".join(FPL[s_] for s_ in FPS) + " & Wrong & No pairs \\\\", "\\midrule"]
for k in KS:
    sup.append(f"{k} & " + " & ".join(f"{fpd[k]['lowest_correct'][s_]:.1f}" for s_ in FPS)
               + f" & {fpd[k]['highest_wrong']:.1f} & {fpd[k]['highest_no_pairs_classic']:.1f} \\\\")
sup += ["\\bottomrule", "\\end{tabular}"]
open(os.path.join(T, "supp_s24_replay_fp.tex"), "w").write("\n".join(sup) + "\n")
derived["fp_pool"] = {"k": fpd,
                      "RB3_min_k": BF["readings"]["RB3"],
                      "k10_lowest_any_score": min(min(v for v in fpd["10"]["lowest_correct"].values()), min(derived["k"]["10"]["lowest_correct"].values())),
                      "never_wrong_k10": fpd["10"]["highest_wrong"] == 0 and derived["k"]["10"]["highest_wrong"] == 0}
derived["n_scores_replayed"] = len(FPS) + len(ORDER)
A2 = json.load(open(os.path.join(D, "S24_A_rest.json")))
derived["fp_pool_accuracy_pp"] = {k: 100 * v["pooled"]["accuracy"] for k, v in A2["results"]["fixed_classic"].items()}
derived["tie_recheck"] = {"cells": len(A2["RA1"]) if isinstance(A2["RA1"], list) else A2["RA1"],
                          "main_A1neg_pct": 100 * A2["results"]["main"]["A1neg"]["pooled"]["accuracy"],
                          "main_A4_pct": 100 * A2["results"]["main"]["A4"]["pooled"]["accuracy"]}

# ---------------- server: paired AP differences ----------------
C = json.load(open(os.path.join(D, "S24_C.json")))["comparisons"]
LAB = [("classic_P1/C1-C0", "Per-call FP $-$ detector", "Five classic, CNOS"),
       ("classic_P1/C4-C0", "Joint FP $-$ detector", ""),
       ("classic_P1/C2-C0", "Reversed FP $-$ detector", ""),
       ("classic_P1/C5-C0", "MegaPose $-$ detector", ""),
       ("classic_P1/C7-C0", "Detector$\\times$depth $-$ detector", ""),
       ("classic_P1/C2-C1", "Reversed FP $-$ per-call FP", ""),
       ("classic_W0/B-W-B-C0", "WBPS $-$ detector", "Five classic, WAPR"),
       ("classic_W0/B-Wneg-B-W", "Reversed WBPS $-$ WBPS", ""),
       ("classic_W0/B-F-B-C0", "FP alone $-$ detector", ""),
       ("xyzibd/C1-C0", "Per-call FP $-$ detector", "XYZ-IBD"),
       ("xyzibd/C2-C1", "Reversed FP $-$ per-call FP", ""),
       ("ipd/C2-C1", "Reversed FP $-$ per-call FP", "IPD")]
assert sorted(k for k, *_ in LAB) == sorted(C)
iv = lambda a: f"[{a[0]:+.2f}, {a[1]:+.2f}]"
rows = ["% generated by scripts/make_s24.py from data33_24/S24_C.json -- do not edit by hand",
        "\\setlength{\\tabcolsep}{4pt}",
        "\\begin{tabular}{@{}ll r c c r c@{}}", "\\toprule",
        " & & \\multicolumn{3}{c}{Images} & \\multicolumn{2}{c}{Scenes} \\\\",
        "\\cmidrule(lr){3-5}\\cmidrule(l){6-7}",
        "Poses & Contrast (AP points) & Diff. & BCa 95\\% & Percentile 95\\% & Diff. & BCa 95\\% \\\\", "\\midrule"]
apd = {}
for key, lab, grp in LAB:
    i, sc = C[key]["image"], C[key]["scene"]
    mark = "" if i["point_in_ci"] else "$^{a}$"
    rows.append(f"{grp} & {lab} & {i['point_pp']:+.2f} & {iv(i['ci95_pp'])}{mark} & {iv(i['percentile_ci95_pp'])} & {sc['point_pp']:+.2f} & {iv(sc['ci95_pp'])} \\\\")
    apd[key] = {"point": i["point_pp"], "bca": i["ci95_pp"], "pct": i["percentile_ci95_pp"], "in_bca": i["point_in_ci"],
                "in_pct": i["point_in_percentile"], "scene_point": sc["point_pp"], "scene_bca": sc["ci95_pp"], "scene_in": sc["point_in_ci"],
                "AP_a": i["AP_a_pp"], "AP_b": i["AP_b_pp"], "jackknife": i.get("normal_jackknife")}
rows += ["\\bottomrule", "\\end{tabular}"]
open(os.path.join(T, "supp_s24_apdiff.tex"), "w").write("\n".join(rows) + "\n")
derived["ap_differences"] = apd
derived["ap_noncover_image"] = sum(not v["in_bca"] for v in apd.values())
derived["ap_noncover_scene"] = sum(not v["scene_in"] for v in apd.values())
derived["ap_n"] = len(apd)
for n in ["S24_RULES_SERVER.json", "S24_B_FP.json", "S24_C.json", "S24_A_rest.json"]:
    derived["inputs"][f"data33_24/{n}"] = sha(os.path.join(D, n))
json.dump(derived, open(os.path.join(D, "derived_s24.json"), "w"), indent=1)
print(open(os.path.join(T, "supp_s24_replay.tex")).read())
print({k: v for k, v in derived.items() if k.startswith(("RB", "k10", "k3"))})
