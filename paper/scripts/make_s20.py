#!/usr/bin/env python3
"""Tables of Supplementary Section S8 and derived numbers of the 33-20 experiments.

Reads data33_20/S20_E1.json, S20_E2.json and S20_E3.json (reversed per-call scores,
calibration on labelled frames, sources of the reversal, scene-level intervals) and writes
  tables/supp_s20_ar.tex, supp_s20_sign.tex, supp_s20_categories.tex,
  supp_s20_cov.tex, supp_s20_scene.tex
  data33_20/derived_s20.json
Usage:  python scripts/make_s20.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(ROOT, "data33_20")
T = os.path.join(ROOT, "tables")
os.makedirs(T, exist_ok=True)
HEAD = "% generated by scripts/make_s20.py from data33_20 -- do not edit by hand\n"
DS = [("lmo", "LM-O"), ("tless", "T-LESS"), ("tudl", "TUD-L"), ("icbin", "IC-BIN"), ("ycbv", "YCB-V")]

e1 = json.load(open(os.path.join(D, "S20_E1.json")))
e2 = json.load(open(os.path.join(D, "S20_E2.json")))
e3 = json.load(open(os.path.join(D, "S20_E3.json")))


def sg(x, nd=2):
    return f"{x:+.{nd}f}".replace("-", "$-$")


def iv(est, lo, hi, nd=2):
    return f"{sg(est, nd)} [{sg(lo, nd)}, {sg(hi, nd)}]"


def ar(d, k, r):
    return e1["AR"][d][k][r]["metrics"]["ar"]["estimate_pp"]


def dif(d, k, r):
    x = e1["paired_AR_differences"][d][k][r]
    return x["estimate_pp"], x["ci95_pp"][0], x["ci95_pp"][1]


# ---------------------------------------------------------------- AR table
rows = [("full", "A1", "Per-call score"), ("full", "A1neg", "Per-call score, sign reversed"),
        ("full", "A10", "Detector $\\times$ depth"), ("full", "A4", "Joint score")]
out = [HEAD, "\\setlength{\\tabcolsep}{4pt}\n\\begin{tabular}{l cccccc}\n\\toprule\n",
       "Ranking score & " + " & ".join(n for _, n in DS) + " & Mean \\\\\n\\midrule\n",
       "\\multicolumn{7}{l}{\\emph{All 2,850 images}}\\\\\n"]
for k, r, lab in rows:
    out.append(f"\\quad {lab} & " + " & ".join(f"{ar(d, k, r):.2f}" for d, _ in DS + [("average", "")]) + " \\\\\n")
out.append("\\multicolumn{7}{l}{\\emph{Images left after removing 10 labelled frames per dataset}}\\\\\n")
for r, lab in (("A1neg", "Per-call score, sign reversed"), ("A1cal10", "Calibrated per source on the labelled frames"), ("A4", "Joint score")):
    out.append(f"\\quad {lab} & " + " & ".join(f"{ar(d, 'k10', r):.2f}" for d, _ in DS + [("average", "")]) + " \\\\\n")
out.append("\\midrule\n\\multicolumn{7}{l}{\\emph{Paired differences of the mean, AR points [95\\% CI]}}\\\\\n")
for k, r, lab in (("full", "A1neg-A4", "Reversed $-$ joint"), ("full", "A1neg-A10", "Reversed $-$ detector $\\times$ depth"),
                  ("k10", "A1cal10-A4", "Calibrated ($k{=}10$) $-$ joint"), ("k5", "A1cal5-A4", "Calibrated ($k{=}5$) $-$ joint"),
                  ("k20", "A1cal20-A4", "Calibrated ($k{=}20$) $-$ joint")):
    out.append(f"\\quad {lab} & \\multicolumn{{6}}{{r}}{{{iv(*dif('average', k, r))}}} \\\\\n")
out.append("\\bottomrule\n\\end{tabular}\n")
open(os.path.join(T, "supp_s20_ar.tex"), "w").write("".join(out))

# ---------------------------------------------------------------- sign learnability
SL = e1["sign_learnability"]
out = [HEAD, "\\setlength{\\tabcolsep}{5pt}\n\\begin{tabular}{c ccc}\n\\toprule\n",
       "Labelled frames $k$ & Lowest share of negative slopes & Combinations at 100\\% & Draws that could not be fitted \\\\\n\\midrule\n"]
sign = {}
for k in ("3", "5", "10", "20"):
    fr = [SL[d][k][s]["fraction_negative"] for d, _ in DS for s in ("CNOS", "NOCTIS")]
    un = sum(SL[d][k][s]["n_unfit"] for d, _ in DS for s in ("CNOS", "NOCTIS"))
    full = sum(1 for x in fr if x >= 1.0)
    sign[k] = {"min_fraction_negative": min(fr), "combos_at_100": full, "unfit": un}
    out.append(f"{k} & {100 * min(fr):.1f}\\% & {full} of {len(fr)} & {un:,} \\\\\n")
out.append("\\bottomrule\n\\end{tabular}\n")
open(os.path.join(T, "supp_s20_sign.tex"), "w").write("".join(out))

# ---------------------------------------------------------------- categories of the incorrect pose
CAT = [("a", "Another object"), ("b", "Target, wrong pose"), ("c", "Background or clutter")]
out = [HEAD, "\\setlength{\\tabcolsep}{4pt}\n\\begin{tabular}{l " + "rr" * 3 + "}\n\\toprule\n",
       " & " + " & ".join(f"\\multicolumn{{2}}{{c}}{{{n}}}" for _, n in CAT) + " \\\\\n",
       "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}\n",
       "Dataset" + " & Pairs & Acc." * 3 + " \\\\\n\\midrule\n"]
for d, n in DS:
    cells = []
    for c, _ in CAT:
        x = e2["by_dataset"][d]["by_wrong_category"][c]
        cells += [f"{x['pairs']:,}", "--" if x["ties_half_accuracy"] is None else f"{100 * x['ties_half_accuracy']:.2f}"]
    out.append(f"{n} & " + " & ".join(cells) + " \\\\\n")
P = e2["pooled"]["by_wrong_category"]
out.append("\\midrule\nPooled & " + " & ".join(f"{P[c]['pairs']:,} & {100 * P[c]['ties_half_accuracy']:.2f}" for c, _ in CAT) + " \\\\\n")
out.append("Share of reversed pairs & " + " & ".join(f"\\multicolumn{{2}}{{r}}{{{100 * P[c]['share_of_reversals']:.2f}\\%}}" for c, _ in CAT) + " \\\\\n")
out.append("\\bottomrule\n\\end{tabular}\n")
open(os.path.join(T, "supp_s20_categories.tex"), "w").write("".join(out))

# ---------------------------------------------------------------- post hoc covariates
CV = e2["pooled"]["post_hoc_covariates"]
COV = [("mask_area", "Mask area"), ("valid_depth_fraction", "Valid depth in the mask"), ("camera_distance_m", "Distance to the camera"),
       ("render_iou", "IoU of rendered and detected mask"), ("visibility", "Visible fraction of the instance")]
out = [HEAD, "\\setlength{\\tabcolsep}{5pt}\n\\begin{tabular}{l cc}\n\\toprule\n",
       "Variable & Correct poses & Incorrect poses \\\\\n\\midrule\n"]
for k, n in COV:
    inc = f"{CV['incorrect'][k]['rho']:+.2f}".replace("-", "$-$") + (" (wrong pose only)" if k == "visibility" else "")
    out.append(f"{n} & {CV['correct'][k]['rho']:+.2f} & {inc} \\\\\n".replace("-0.", "$-$0.") .replace("+$-$", "$-$"))
out.append(f"\\midrule\nPoses & {CV['correct']['mask_area']['n']:,} & {CV['incorrect']['mask_area']['n']:,} \\\\\n")
out.append("\\bottomrule\n\\end{tabular}\n")
open(os.path.join(T, "supp_s20_cov.tex"), "w").write("".join(out))

# ---------------------------------------------------------------- scene-level intervals
R = e3["results"]
out = [HEAD, "\\setlength{\\tabcolsep}{4pt}\n\\begin{tabular}{l l c c}\n\\toprule\n",
       "Scope & Comparison & Resampling images & Resampling scenes \\\\\n\\midrule\n"]
scene = {}
ew = R["table1"]["equal_weight_average"]
for cmp_, lab in (("A4-A1", "Joint $-$ per-call"), ("A4-A10", "Joint $-$ detector $\\times$ depth"), ("A4-A5", "Joint $-$ MegaPose"), ("A1neg-A4", "Reversed $-$ joint")):
    x = ew["comparisons"][cmp_]
    bi, bs = x["by_image"], x["by_scene"]
    scene[f"table1_{cmp_}"] = {"image": bi["ci95_pp"], "scene": bs["ci95_pp"], "estimate": bi["estimate_pp"]}
    out.append(f"Table 1, T-LESS and YCB-V & {lab} & {iv(bi['estimate_pp'], *bi['ci95_pp'])} & {iv(bs['estimate_pp'], *bs['ci95_pp'])} \\\\\n")
out.append("\\midrule\n")
for d, n in (("xyzibd", "XYZ-IBD"), ("ipd", "IPD")):
    for cmp_ in ("B4-B0", "B4-B1", "B4-B3"):
        x = R["table4"][d]["comparisons"][cmp_]
        bi, bs = x["by_image"], x["by_scene"]
        scene[f"{d}_{cmp_}"] = {"image": bi["ci95_pp"], "scene": bs["ci95_pp"], "estimate": bi["estimate_pp"]}
        out.append(f"Table 5, {n} & {cmp_.replace('-', ' $-$ ')} & {iv(bi['estimate_pp'], *bi['ci95_pp'])} & {iv(bs['estimate_pp'], *bs['ci95_pp'])} \\\\\n")
out.append("\\midrule\n")
for key, n in (("ipd tau 0.2", "IPD, $\\tau=0.20$"), ("ipd tau 0.26", "IPD, $\\tau=0.26$"), ("ipd tau 0.29", "IPD, $\\tau=0.29$"), ("ipd tau 0.32", "IPD, $\\tau=0.32$")):
    x = R["section_6_4"][key]["comparisons"]["B4-B1"]
    bi, bs = x["by_image"], x["by_scene"]
    scene[key.replace(" ", "_")] = {"image": bi["ci95_pp"], "scene": bs["ci95_pp"], "estimate": bi["estimate_pp"]}
    out.append(f"Count-ratio sweep, {n} & B4 $-$ B1 & {iv(bi['estimate_pp'], *bi['ci95_pp'])} & {iv(bs['estimate_pp'], *bs['ci95_pp'])} \\\\\n")
out.append("\\bottomrule\n\\end{tabular}\n")
open(os.path.join(T, "supp_s20_scene.tex"), "w").write("".join(out))

# ---------------------------------------------------------------- derived numbers quoted in the text
pa = e1["pair_accuracy"]["pooled"]["full"]
derived = {
    "AR_full_mean": {r: ar("average", "full", r) for r in ("A1", "A1neg", "A4", "A10")},
    "AR_k10_mean": {r: ar("average", "k10", r) for r in ("A1neg", "A1cal10", "A4")},
    "diff": {f"{k}:{r}": dif("average", k, r) for k, r in (("full", "A1neg-A4"), ("full", "A1neg-A10"), ("full", "A1neg-A1"),
                                                           ("k10", "A1cal10-A4"), ("k5", "A1cal5-A4"), ("k20", "A1cal20-A4"))},
    "pairwise_reversed_strict_pct": 100 * pa["A1neg"]["ties_half_accuracy"],
    "pairwise_reversed_ties": pa["A1neg"]["ties"],
    "pairwise_joint_strict_pct": 100 * pa["A4"]["ties_half_accuracy"],
    "sign_learnability": sign,
    "categories": {c: {"pairs": P[c]["pairs"], "strict_pct": 100 * P[c]["ties_half_accuracy"], "share_pct": 100 * P[c]["share_of_reversals"]} for c, _ in CAT},
    "category_differences": {k: (v["estimate_pp"], v["ci95_pp"][0], v["ci95_pp"][1]) for k, v in e2["pooled"]["strict_accuracy_differences_pp"].items()},
    "covariates": {g: {k: CV[g][k]["rho"] for k, _ in COV} for g in ("correct", "incorrect")},
    "scene": scene,
    "readings": {**e1["reading"], "R5": e2["R5"]},
}
json.dump(derived, open(os.path.join(D, "derived_s20.json"), "w"), indent=1, sort_keys=True)
print("wrote 5 tables and data33_20/derived_s20.json")
