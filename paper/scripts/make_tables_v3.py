#!/usr/bin/env python3
"""Tables 2-5 of the analysis-first manuscript, generated from the 33-17 deliverables.

Usage: python3 scripts/make_tables_v3.py      (run from the manuscript root)
Inputs : data33_17/TABLES_P1.md, TABLES_P2.md (auto-generated by tables33_17.py from the result JSON),
         data33_17/ED_MECH.json, Y7_IPD.json, Y7_XYZIBD.json
Outputs: tables/tab_rankings.tex, tab_pairwise.tex, tab_counterfactual.tex, tab_counts.tex
No number is typed by hand in this script.
"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(ROOT, "data33_17"); T = os.path.join(ROOT, "tables")
HEAD = "% generated by scripts/make_tables_v3.py from data33_17 -- do not edit by hand\n"


def md_table(fname, title):
    rows, on = [], False
    for line in open(os.path.join(D, fname), encoding="utf8"):
        if line.startswith("## "):
            on = line[3:].strip() == title
            continue
        if on and line.startswith("|") and not line.startswith("| ---"):
            rows.append([c.strip() for c in line.strip().strip("|").split("|")])
    assert rows, (fname, title)
    return rows[1:]


def ci(s, sign=True):
    """'47.82 [47.17, 48.51]' -> LaTeX with explicit signs."""
    m = re.match(r"(-?[\d.]+) \[(-?[\d.]+), (-?[\d.]+)\]", s)
    v, lo, hi = (float(x) for x in m.groups())
    f = (lambda x: f"${x:+.2f}$".replace("-", "{-}")) if sign else (lambda x: f"{x:.2f}")
    g = lambda x: f"{x:+.2f}".replace("-", "$-$").replace("+", "+")
    return f"{g(v)} [{g(lo)}, {g(hi)}]"


def num(x):
    return f"{float(x):.2f}".replace("-", "$-$")


