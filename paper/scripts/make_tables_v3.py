def tab_rankings():
    ar = {r[0]: r[1:] for r in md_table("TABLES_P1.md", "E-A 与 X2 的 AR（百分点）")}
    d1 = {r[0]: r[-1] for r in md_table("TABLES_P1.md", "E-A 的配对差（百分点）")}
    d2 = {r[0]: r[-1] for r in md_table("TABLES_P1.md", "X2 的配对差（百分点）")}
    diff = {"A1": d1["A4-A1"], "A2": d1["A4-A2"], "A3": d1["A4-A3"], "A5": d1["A4-A5"],
            "A7": d2["A4-A7"], "A8": d2["A4-A8"], "A9": d2["A4-A9"], "A10": d2["A4-A10"]}
    groups = [
        ("FoundationPose scores taken from separate calls", [
            ("A1", "Per-call score"), ("A7", "$z$-score within its call"),
            ("A8", "Softmax within its call"), ("A9", "Margin over the runner-up")]),
        ("Scores that do not depend on the other hypotheses", [
            ("A2", "Detector confidence"), ("A3", "Depth consistency"),
            ("A10", "Detector $\\times$ depth"), ("A5", "MegaPose score")]),
        ("FoundationPose, all best poses of an object in one call", [("A4", "Joint score")]),
    ]
    s20 = os.path.join(os.path.dirname(os.path.abspath(D)), "data33_20", "S20_E1.json")
    if os.path.exists(s20):  # 33-20: the per-call score with its sign reversed, same best poses and selection
        e1 = json.load(open(s20))
        ar["A1neg"] = [f"{e1['AR'][d]['full']['A1neg']['metrics']['ar']['estimate_pp']:.2f}" for d in ("lmo", "tless", "tudl", "icbin", "ycbv", "average")]
        x = e1["paired_AR_differences"]["average"]["full"]["A1neg-A4"]
        diff["A1neg"] = f"{-x['estimate_pp']:.2f} [{-x['ci95_pp'][1]:.2f}, {-x['ci95_pp'][0]:.2f}]"
        groups[0][1].insert(1, ("A1neg", "Per-call score, sign reversed"))
    comparable = [k for _, g in groups for k, _ in g]
    best = [max(comparable, key=lambda k: float(ar[k][c])) for c in range(6)]
    out = [HEAD, "\\setlength{\\tabcolsep}{3pt}\n\\adjustbox{max width=\\linewidth}{%\n\\begin{tabular}{l ccccc c l}\n\\toprule\n",
           "Ranking score & LM-O & T-LESS & TUD-L & IC-BIN & YCB-V & Mean & Joint $-$ row [95\\% CI] \\\\\n\\midrule\n"]
    for title, g in groups:
        out.append(f"\\multicolumn{{8}}{{l}}{{\\emph{{{title}}}}}\\\\\n")
        for k, lab in g:
            cells = [("\\textbf{%s}" % num(v)) if best[c] == k else num(v) for c, v in enumerate(ar[k])]
            out.append(f"\\quad {lab} & " + " & ".join(cells) + " & " + (ci(diff[k]) if k in diff else "--") + " \\\\\n")
    out.append("\\midrule\n\\multicolumn{8}{l}{\\emph{Masks of one detector only}}\\\\\n")
    for a, b, lab, key in (("A1c", "A4c", "CNOS", "A4c-A1c"), ("A1n", "A4n", "NOCTIS", "A4n-A1n")):
        out.append(f"\\quad {lab}, per-call score & " + " & ".join(num(x) for x in ar[a]) + " & " + ci(d2[key]) + " \\\\\n")
        out.append(f"\\quad {lab}, joint score & " + " & ".join(num(x) for x in ar[b]) + " & -- \\\\\n")
    out.append("\\bottomrule\n\\end{tabular}\n}\n")
    open(os.path.join(T, "tab_rankings.tex"), "w").write("".join(out))


