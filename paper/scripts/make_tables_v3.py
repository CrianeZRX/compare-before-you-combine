def tab_counterfactual():
    spec = [("X1 LM-O A1", "TABLES_P1.md"), ("X1 LM-O A4", "TABLES_P1.md"), ("X1 T-LESS A1", "TABLES_P1.md"), ("X1 T-LESS A4", "TABLES_P1.md"),
            ("X1 IC-BIN A1", "TABLES_P1.md"), ("X1 IC-BIN A4", "TABLES_P1.md"), ("X1 IPD B1", "TABLES_P1.md")]
    cols = []
    for title, f in spec:
        r = {x[0]: x for x in md_table(f, title)}
        cols.append({"base": float(r["Base"][1]), "all": float(r["All"][2]),
                     **{k: (float(r[k][2]) if k in r else None) for k in ("Fmask", "Fpose", "Fcov", "Fid", "Fsel", "Fcount")}})
    y = {x[0]: float(x[1]) for x in md_table("TABLES_P2.md", "Y1 反事实") if x[0].startswith("F") or x[0] == "All"}
    b1 = [x for x in md_table("TABLES_P2.md", "Y1 XYZ-IBD") if x[0] == "B1"][0]
    cols.append({"base": float(b1[1]), "all": y["All"], **{k: y[k] for k in ("Fmask", "Fpose", "Fcov", "Fid", "Fsel", "Fcount")}})
    rows = [("base", "Baseline AR or AP"), None, ("Fmask", "Mask quality: true masks where covered"),
            ("Fpose", "Pose accuracy: true poses for near misses"), None,
            ("Fcov", "Coverage: true masks where uncovered"), ("Fid", "Identity: drop masks of other objects"),
            ("Fsel", "Selection: oracle among best poses"), ("Fcount", "Count: true identities and counts"), None, ("all", "All repairs together")]
    main = {}
    out = [HEAD, "\\setlength{\\tabcolsep}{3pt}\n\\adjustbox{max width=\\linewidth}{%\n\\begin{tabular}{l rr rr rr r r}\n\\toprule\n",
           " & \\multicolumn{6}{c}{Localization (AR)} & \\multicolumn{2}{c}{Detection (AP)} \\\\\n\\cmidrule(lr){2-7}\\cmidrule(lr){8-9}\n",
           " & \\multicolumn{2}{c}{LM-O} & \\multicolumn{2}{c}{T-LESS$^{a}$} & \\multicolumn{2}{c}{IC-BIN} & IPD & XYZ-IBD \\\\\n",
           "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}\n",
           "Repair (gain in points) & per-call & joint & per-call & joint & per-call & joint & joint & joint \\\\\n\\midrule\n"]
    singles = ("Fmask", "Fpose", "Fcov", "Fid", "Fsel", "Fcount")
    top = [max((k for k in singles if c[k] is not None), key=lambda k: c[k]) for c in cols]
    for r in rows:
        if r is None:
            out.append("\\addlinespace[2pt]\n"); continue
        k, lab = r
        cells = []
        for j, c in enumerate(cols):
            v = c[k]
            if v is None: cells.append("--")
            elif k == "base": cells.append(f"{v:.2f}")
            else:
                s = f"{v:+.2f}".replace("-", "$-$")
                cells.append("\\textbf{%s}" % s if (k in singles and top[j] == k) else s)
        out.append(f"{lab} & " + " & ".join(cells) + " \\\\\n")
    out.append("\\bottomrule\n\\end{tabular}\n}\n")
    open(os.path.join(T, "tab_counterfactual.tex"), "w").write("".join(out))
    return cols


