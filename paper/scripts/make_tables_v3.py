def tab_counts():
    y7 = {"x": json.load(open(os.path.join(D, "Y7_XYZIBD.json"))), "i": json.load(open(os.path.join(D, "Y7_IPD.json")))}
    truth = {k: sum(f["truth_count"] for f in v["per_frame"]) for k, v in y7.items()}
    ap = {"x": {r[0]: r[1] for r in md_table("TABLES_P2.md", "Y1 XYZ-IBD")}, "i": {r[0]: r[1] for r in md_table("TABLES_P1.md", "EB 评测")}}
    df = {"x": {r[0]: r[1] for r in md_table("TABLES_P2.md", "Y1 配对差")}, "i": {r[0]: r[1] for r in md_table("TABLES_P1.md", "EB 配对差")}}
    desc = {"B0": ("One pose per detection, no selection across masks", "detections"),
            "B1": ("Joint scoring per object", "detector count"),
            "B2": ("Joint scoring per object", "verified poses"),
            "B3": ("Joint scoring + supplementary candidates", "detector count"),
            "B4": ("Joint scoring + supplementary candidates", "verified poses")}
    out = [HEAD, "\\setlength{\\tabcolsep}{3.5pt}\n\\adjustbox{max width=\\linewidth}{%\n\\begin{tabular}{l l l cc cc}\n\\toprule\n",
           " & & & \\multicolumn{2}{c}{XYZ-IBD} & \\multicolumn{2}{c}{IPD} \\\\\n\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}\n",
           "Row & Candidates and scoring & Output count from & AP & Outputs$^{a}$ & AP & Outputs$^{a}$ \\\\\n\\midrule\n"]
    for r in ("B0", "B1", "B2", "B3", "B4"):
        cells = []
        for k in ("x", "i"):
            n = y7[k]["rows"][r]["outputs"] / truth[k]
            a = ap[k][r]
            cells += [("\\textbf{%s}" % a) if a == max(ap[k].values(), key=float) else a, f"{n:.2f}"]
        out.append(f"{r} & {desc[r][0]} & {desc[r][1]} & " + " & ".join(cells) + " \\\\\n")
    out.append("\\midrule\n\\multicolumn{3}{l}{\\emph{Paired differences, AP points [95\\% CI]}} & \\multicolumn{2}{c}{XYZ-IBD} & \\multicolumn{2}{c}{IPD} \\\\\n")
    for key, lab in (("B1-B0", "B1 $-$ B0: joint scoring alone"), ("B2-B1", "B2 $-$ B1: count rule alone"), ("B3-B1", "B3 $-$ B1: supplementary candidates alone"),
                     ("B4-B3", "B4 $-$ B3: count rule, given the candidates"), ("B4-B0", "B4 $-$ B0: both together")):
        out.append(f"\\multicolumn{{3}}{{l}}{{{lab}}} & \\multicolumn{{2}}{{c}}{{{ci(df['x'][key])}}} & \\multicolumn{{2}}{{c}}{{{ci(df['i'][key])}}} \\\\\n")
    out.append("\\midrule\n\\multicolumn{3}{l}{\\emph{Detector counts per frame, median [quartiles]}} & \\multicolumn{2}{c}{XYZ-IBD} & \\multicolumn{2}{c}{IPD} \\\\\n")
    q = lambda d: f"{d['median']:.2f} [{d['q1']:.2f}, {d['q3']:.2f}]"
    for key, lab in (("detector_all", "Detections per annotated instance (count ratio)"), ("per_true_object", "Detections of a present object per instance of it"),
                     ("object_species", "Identities reported per identity present")):
        out.append(f"\\multicolumn{{3}}{{l}}{{{lab}}} & \\multicolumn{{2}}{{c}}{{{q(y7['x']['counts'][key])}}} & \\multicolumn{{2}}{{c}}{{{q(y7['i']['counts'][key])}}} \\\\\n")
    out.append("\\bottomrule\n\\end{tabular}\n}\n")
    open(os.path.join(T, "tab_counts.tex"), "w").write("".join(out))
    return truth


