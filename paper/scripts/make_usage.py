#!/usr/bin/env python3
"""Supplementary Section S9: how public BOP entries describe their use of FoundationPose.
Reads data_survey/BOP_USAGE_20261119.json (transcribed by hand from the BOP method pages) and writes
tables/supp_usage.tex and data_survey/derived_usage.json.
Usage:  python scripts/make_usage.py
"""
import json, os
from collections import OrderedDict
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
D = os.path.join(ROOT, "data_survey"); T = os.path.join(ROOT, "tables"); os.makedirs(T, exist_ok=True)
d = json.load(open(os.path.join(D, "BOP_USAGE_20261119.json"), encoding="utf8"))
E = d["classic_core_localization"]["entries"]
fams = OrderedDict()
for e in E:
    fams.setdefault(e["family"], []).append(e)
def role(es):
    r = [e["foundationpose_role"] for e in es]
    n = len(es)
    k = lambda v: sum(x == v for x in r)
    if k("scorer"): return "score network" + ("" if k("scorer") == n else " (%d of %d pages)" % (k("scorer"), n))
    if k("refiner") == n: return "refinement"
    if k("role not stated"): return "used, role not stated" + ("" if k("role not stated") == n else " (%d of %d pages)" % (k("role not stated"), n))
    if k("the method itself"): return "the method itself"
    if k("none"): return "not used"
    return "no description"
def chosen(es):
    s = [e["final_pose_chosen_by"] for e in es if e["final_pose_chosen_by"] != "not stated"]
    if not s: return "not stated"
    if any(x.startswith("FoundationPose") for x in s): return "highest FoundationPose score per detection"
    if "own selection network" in s: return "own selection network"
    return s[0]
out = ["% generated by scripts/make_usage.py from data_survey/BOP_USAGE_20261119.json -- do not edit by hand\n",
       "\\begin{tabular}{@{}l l l l l@{}}\n\\toprule\n",
       "Method family & Ranks & FoundationPose & Final pose chosen by & Confidence \\\\\n\\midrule\n"]
for f, es in fams.items():
    out.append("%s & %s & %s & %s & %s \\\\\n" % (f, ", ".join(str(e["rank"]) for e in es), role(es), chosen(es),
                                                 "not stated" if all(e["confidence"] == "not stated" for e in es) else "stated"))
out.append("\\bottomrule\n\\end{tabular}\n")
open(os.path.join(T, "supp_usage.tex"), "w").write("".join(out))
ind = d["industrial_detection"]["entries"]
derived = {
 "read_on": d["read_on"], "n_entries": len(E),
 "n_use_foundationpose": sum(e["uses_foundationpose"] for e in E),
 "n_state_score_network_selects": sum(e["foundationpose_role"] == "scorer" for e in E),
 "n_state_refiner": sum(e["foundationpose_role"] == "refiner" for e in E),
 "n_state_confidence": sum(e["confidence"] != "not stated" for e in E),
 "n_state_ranking_across_detections": sum(e["ranking_across_detections"] != "not stated" for e in E),
 "n_without_description": sum(not e["has_description"] for e in E),
 "industrial_submit_fp_score": [e["name"] for e in ind if e["confidence"] == "FoundationPose score"],
}
json.dump(derived, open(os.path.join(D, "derived_usage.json"), "w"), indent=1, sort_keys=True)
print("wrote tables/supp_usage.tex and data_survey/derived_usage.json"); print(derived)
