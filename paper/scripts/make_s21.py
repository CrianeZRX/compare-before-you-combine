#!/usr/bin/env python3
"""Table of Supplementary Section S8.4 and derived numbers of the 33-21 checks.

Reads data33_19/S19_E2.json (count ratios of the five classic datasets, IPD and XYZ-IBD at the
official NOCTIS threshold) and data33_21 (count ratios of HomebrewedDB and HOPE-Image on the same
GPU path; the pilot scorer). Writes tables/supp_s21_ratios.tex and data33_21/derived_s21.json.
Usage:  python scripts/make_s21.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
T = os.path.join(ROOT, "tables")
os.makedirs(T, exist_ok=True)
s19 = json.load(open(os.path.join(ROOT, "data33_19", "S19_E2.json")))
d19 = json.load(open(os.path.join(ROOT, "data33_19", "derived_s19.json")))
D21 = os.path.join(ROOT, "data33_21")
hb = json.load(open(os.path.join(D21, "S21_E0B_GPU_HB.json")))["summary"]
hope = json.load(open(os.path.join(D21, "S21_E0B_GPU_HOPE.json")))["summary"]
e2 = json.load(open(os.path.join(D21, "S21_E2.json")))
e1 = json.load(open(os.path.join(D21, "S21_E1.json")))

five = s19["condition_source"]["E2b"]["realized"]["all_five"]
off = lambda ds: s19["E2a"][ds]["threshold_results"]["0.2"]["offline_2D_condition"]
eff = {c["ds"]: c for c in d19["E2"]["conditions"] if abs(c["tau"] - 0.2) < 1e-9}
rows = [("LM-O", five["lmo"], None), ("T-LESS", five["tless"], None), ("TUD-L", five["tudl"], "tudl"),
        ("IC-BIN", five["icbin"], "icbin"), ("YCB-V", five["ycbv"], None), ("IPD", off("ipd"), "ipd"),
        ("HomebrewedDB", hb, None), ("HOPE-Image", hope, None), ("XYZ-IBD", off("xyzibd"), "xyzibd")]


def sg(x):
    return f"{x:+.2f}".replace("-", "$-$")


out = ["% generated by scripts/make_s21.py -- do not edit by hand\n",
       "\\setlength{\\tabcolsep}{5pt}\n\\begin{tabular}{l r c c c}\n\\toprule\n",
       "Dataset & Frames & Median count ratio & Frames below one & B4 $-$ B1 (AP) [95\\% CI] \\\\\n\\midrule\n"]
ratios = {}
for name, r, k in rows:
    ratios[name] = r["median_count_ratio"]
    n = r.get("valid_ratio_frames", r.get("frames"))
    cell = "--" if k is None else f"{sg(eff[k]['delta'])} [{sg(eff[k]['ci'][0])}, {sg(eff[k]['ci'][1])}]"
    out.append(f"{name} & {n} & {r['median_count_ratio']:.2f} & {100 * r['fraction_ratio_below_one']:.0f}\\% & {cell} \\\\\n")
out.append("\\bottomrule\n\\end{tabular}\n")
open(os.path.join(T, "supp_s21_ratios.tex"), "w").write("".join(out))

A = e2["variants"]["A"]["pooled"]
derived = {
    "median_count_ratio": ratios,
    "n_datasets": len(ratios),
    "n_under_reporting": sum(1 for v in ratios.values() if v < 1),
    "e1_status": e1["status"],
    "pilot_A": {"cross_call_pct": 100 * A["cross_context"]["strict"], "cross_call_ci_pct": [100 * x for x in A["cross_context"]["ci95"]],
                "alone_pct": 100 * A["cross_single"]["strict"], "within_pct": 100 * A["within"]["strict"],
                "background_pct": 100 * A["background"]["strict"], "other_object_pct": 100 * A["other_object"]["strict"],
                "target_wrong_pct": 100 * A["target_pose_wrong"]["strict"]},
    "e2_status": e2["status"],
}
json.dump(derived, open(os.path.join(D21, "derived_s21.json"), "w"), indent=1, sort_keys=True)
print("wrote tables/supp_s21_ratios.tex and data33_21/derived_s21.json")
