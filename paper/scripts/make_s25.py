#!/usr/bin/env python3
"""Tables and derived numbers of 33-25: the released check with its six-image rule (data33_25/).

Usage:  python scripts/make_s25.py          (run from the manuscript root, after make_s24.py)
Inputs: data33_25/S25_RULES.json, S25_RULES_AMEND.json   rules, written before any result
        data33_25/S25_null.json      random-sign control: k random frames, each keeping or negating its scores
        data33_25/S25_seqnull.json   the same control when frames are labelled until ten hold a pair
        data33_25/S25_replay.json    replay of 33-24 with the gated check (same draws and tool seeds)
        data33_25/S25_seq.json       frames labelled in random order until 6 or 10 hold a pair
        data33_25/S25_full.json      the gated check on all frames
        (run25.py in the same folder produced all of them from the 33-24 rows; tool_check_v1_1.py is the check)
        data33_25/S25_PUBLIC_RULES.json, S25_PUBLIC.json, REPORT33_25_S.md
                                     server deliverables of 33-25-S: the same check on the public submission files
Outputs:
  tables/tab_sign.tex              main text: reading of the per-call FoundationPose score, and the random-sign control
  tables/supp_s25_replay_fp.tex    lowest share of correct readings over the five datasets, FoundationPose poses
  tables/supp_s25_replay.tex       the same on the WAPR poses
  tables/supp_s25_null.tex         share of draws read in either direction under random signs, with and without the rule
  tables/supp_s25_seq.tex          labelling until ten frames hold a pair: frames needed and readings
  data33_25/derived_s25.json       numbers quoted in the text
"""
import json, os, hashlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(ROOT, "data33_25"); T = os.path.join(ROOT, "tables")
sha = lambda p: hashlib.sha256(open(p, "rb").read()).hexdigest()
load = lambda n: json.load(open(os.path.join(D, n)))
RULES_SHA = sha(os.path.join(D, "S25_RULES.json"))
AMEND_SHA = sha(os.path.join(D, "S25_RULES_AMEND.json"))
CL = ["lmo", "tless", "tudl", "icbin", "ycbv"]
SIX = CL + ["xyzibd"]
NAME = {"lmo": "LM-O", "tless": "T-LESS", "tudl": "TUD-L", "icbin": "IC-BIN", "ycbv": "YCB-V", "xyzibd": "XYZ-IBD"}
GEN = "% generated by scripts/make_s25.py from data33_25 -- do not edit by hand"


def cells(name):
    d = load(name)
    assert d["rules_sha256"] == RULES_SHA, f"{name} was not run under S25_RULES.json"
    return {tuple(c["key"][1:]): c["result"] for c in d["cells"]}


null, seqnull, rep, seq, full = (cells(n) for n in
                                 ("S25_null.json", "S25_seqnull.json", "S25_replay.json", "S25_seq.json", "S25_full.json"))
FPP, XP, WP = "classic_33_19_E1", "xyzibd_33_19_E1e_B1", "wapr_33_22_E4"
pool = lambda ds: XP if ds == "xyzibd" else FPP
KS = [3, 5, 10, 20]

# ---------------- main table: per-call FoundationPose score ----------------
fp = {}
for k in KS:
    rc = [rep[(FPP, d, "fp_raw", k)]["v1.1"]["correct"] for d in CL]
    nc = [null[(d, "fp_raw", k)]["v1.1"]["definite_pct"] for d in CL]
    fp[k] = {"classic_lowest": min(rc), "xyz": rep[(XP, "xyzibd", "fp_raw", k)]["v1.1"]["correct"],
             "null_classic_highest": max(nc), "null_xyz": null[("xyzibd", "fp_raw", k)]["v1.1"]["definite_pct"],
             "null_v10_classic_highest": max(null[(d, "fp_raw", k)]["v1.0"]["definite_pct"] for d in CL),
             "null_v10_xyz": null[("xyzibd", "fp_raw", k)]["v1.0"]["definite_pct"],
             "informative_median": {d: rep[(pool(d), d, "fp_raw", k)]["informative_images"]["median"] for d in SIX}}
sq = {d: seq[(pool(d), d, "fp_raw", 10)] for d in SIX}
sqn = {d: seqnull[(d, "fp_raw")]["definite_pct"] for d in SIX}
fl = {d: sq[d]["frames_labelled"] for d in SIX}
lines = [GEN, "\\setlength{\\tabcolsep}{4pt}",
         "\\begin{tabular}{@{}l cc cc@{}}", "\\toprule",
         " & \\multicolumn{2}{c}{Read as reversed} & \\multicolumn{2}{c}{Random signs} \\\\",
         "\\cmidrule(lr){2-3}\\cmidrule(l){4-5}",
         "Frames & Classic & XYZ-IBD & Classic & XYZ-IBD \\\\", "\\midrule"]
for k in (10, 20):
    v = fp[k]
    lines.append(f"{k} random & {v['classic_lowest']:.1f}\\% & {v['xyz']:.1f}\\% & {v['null_classic_highest']:.1f}\\% & {v['null_xyz']:.1f}\\% \\\\")
lines.append("Ten with a pair & %.1f\\%% & %.1f\\%% & %.1f\\%% & %.1f\\%% \\\\" % (
    min(sq[d]["correct"] for d in CL), sq["xyzibd"]["correct"], max(sqn[d] for d in CL), sqn["xyzibd"]))
lines += ["\\bottomrule", "\\end{tabular}"]
open(os.path.join(T, "tab_sign.tex"), "w").write("\n".join(lines) + "\n")

# ---------------- supplement: replay tables ----------------
def replay_table(p, scores, labels, rev, fname):
    out = [GEN, "\\setlength{\\tabcolsep}{4pt}",
           "\\begin{tabular}{@{}c " + "c" * len(rev) + " " + "c" * (len(scores) - len(rev)) + " ccc@{}}", "\\toprule",
           " & \\multicolumn{%d}{c}{Should read reversed} & \\multicolumn{%d}{c}{Should read comparable} & \\multicolumn{3}{c}{Any score} \\\\"
           % (len(rev), len(scores) - len(rev)),
           "\\cmidrule(lr){2-%d}\\cmidrule(lr){%d-%d}\\cmidrule(l){%d-%d}" % (1 + len(rev), 2 + len(rev), 1 + len(scores), 2 + len(scores), 4 + len(scores)),
           "$k$ & " + " & ".join(labels[s] for s in scores) + " & Wrong & Too few & No pairs \\\\", "\\midrule"]
    res = {}
    for k in KS:
        low = {s: min(rep[(p, d, s, k)]["v1.1"]["correct"] for d in CL) for s in scores}
        wrong = max(rep[(p, d, s, k)]["v1.1"]["wrong"] for d in CL for s in scores)
        nop = max(rep[(p, d, s, k)]["v1.1"]["no_pairs"] for d in CL for s in scores)
        few = max(rep[(p, d, s, k)]["informative_images"]["share_lt6_pct"] - rep[(p, d, s, k)]["v1.1"]["no_pairs"]
                  for d in CL for s in scores)
        out.append(f"{k} & " + " & ".join(f"{low[s]:.1f}" for s in scores) + f" & {wrong:.1f} & {few:.1f} & {nop:.1f} \\\\")
        res[k] = {"lowest_correct": low, "highest_wrong": wrong, "highest_no_pairs": nop, "highest_lt6": few}
    out += ["\\bottomrule", "\\end{tabular}"]
    open(os.path.join(T, fname), "w").write("\n".join(out) + "\n")
    return res


FPS = ["fp_raw", "fp_single", "fp_joint", "megapose_single", "depth", "mask_iou", "chamfer"]
FPL = {"fp_raw": "FP per call", "fp_single": "FP alone", "fp_joint": "FP joint", "megapose_single": "MegaPose",
       "depth": "Depth cons.", "mask_iou": "Mask IoU", "chamfer": "Chamfer"}
WS = ["fp_single", "wbps_neg", "wbps_raw", "wbps_single", "depth", "fp_joint"]
WL = {"fp_single": "FP alone", "wbps_neg": "WBPS reversed", "wbps_raw": "WBPS", "wbps_single": "WBPS alone",
      "depth": "Depth cons.", "fp_joint": "FP joint"}
rfp = replay_table(FPP, FPS, FPL, ["fp_raw", "fp_single"], "supp_s25_replay_fp.tex")
rw = replay_table(WP, WS, WL, ["fp_single", "wbps_neg"], "supp_s25_replay.tex")

# ---------------- supplement: random-sign control ----------------
out = [GEN, "\\setlength{\\tabcolsep}{4pt}", "\\begin{tabular}{@{}cl " + "c" * 6 + "@{}}", "\\toprule",
       "$k$ & Check & " + " & ".join(NAME[d] for d in SIX) + " \\\\", "\\midrule"]
for k in KS:
    for t, lab in (("v1.0", "without the rule"), ("v1.1", "released")):
        vals = [max(null[(d, s, k)][t]["definite_pct"] for s in ("fp_raw", "depth")) for d in SIX]
        out.append((f"{k}" if t == "v1.0" else "") + f" & {lab} & " + " & ".join(f"{v:.1f}" for v in vals) + " \\\\")
    if k != KS[-1]:
        out.append("\\addlinespace[2pt]")
out.append("\\addlinespace[2pt]")
out.append("Until ten & released & " + " & ".join(f"{max(seqnull[(d, s)]['definite_pct'] for s in ('fp_raw', 'depth')):.1f}" for d in SIX) + " \\\\")
out += ["\\bottomrule", "\\end{tabular}"]
open(os.path.join(T, "supp_s25_null.tex"), "w").write("\n".join(out) + "\n")

# ---------------- supplement: sequential labelling ----------------
ALLP = [(FPP, FPS), (WP, WS)]
out = [GEN, "\\setlength{\\tabcolsep}{4pt}", "\\begin{tabular}{@{}l ccc cc@{}}", "\\toprule",
       " & \\multicolumn{3}{c}{Frames labelled} & \\multicolumn{2}{c}{Correct readings (\\%)} \\\\",
       "\\cmidrule(lr){2-4}\\cmidrule(l){5-6}",
       "Dataset & Median & 90th pct. & Most & FP per call & Lowest other score \\\\", "\\midrule"]
seq_low_other = {}
for d in SIX:
    f = fl[d]
    others = [seq[(p, d, s, 10)]["correct"] for p, ss in ALLP for s in ss if s != "fp_raw" and (p, d, s, 10) in seq]
    if d == "xyzibd":
        others = [seq[(XP, d, "depth", 10)]["correct"]]
    seq_low_other[d] = min(others)
    out.append(f"{NAME[d]} & {f['median']} & {f['p90']} & {f['max']} & {sq[d]['correct']:.1f} & {min(others):.1f} \\\\")
out += ["\\bottomrule", "\\end{tabular}"]
open(os.path.join(T, "supp_s25_seq.tex"), "w").write("\n".join(out) + "\n")

# ---------------- derived numbers and criteria ----------------
null_v11 = [v["v1.1"]["definite_pct"] for v in null.values()]
null_v10 = [v["v1.0"]["definite_pct"] for v in null.values()]
wrong_any = max([v["v1.1"]["wrong"] for v in rep.values()] + [v["wrong"] for v in seq.values()])
derived = {
    "inputs": {n: sha(os.path.join(D, n)) for n in ["S25_RULES.json", "S25_RULES_AMEND.json", "S25_null.json", "S25_seqnull.json",
                                                    "S25_replay.json", "S25_seq.json", "S25_full.json", "run25.py", "tool_check_v1_1.py"]},
    "fp": {str(k): v for k, v in fp.items()},
    "seq_fp": {d: {"correct": sq[d]["correct"], "frames": fl[d]} for d in SIX},
    "seq_null_fp": sqn,
    "seq_low_other": seq_low_other,
    "seq_lowest_any_score_classic": min(seq[(p, d, s, 10)]["correct"] for p, ss in ALLP for s in ss for d in CL),
    "seq_frames_median_classic": [min(fl[d]["median"] for d in CL), max(fl[d]["median"] for d in CL)],
    "null_v11_max": max(null_v11), "null_v10_max": max(null_v10),
    "null_v11_mean_k10": sum(v["v1.1"]["definite_pct"] for (d, s, k), v in null.items() if k == 10) / 12,
    "null_v10_classic_k10_range": [min(null[(d, s, 10)]["v1.0"]["definite_pct"] for d in CL for s in ("fp_raw", "depth")),
                                   max(null[(d, s, 10)]["v1.0"]["definite_pct"] for d in CL for s in ("fp_raw", "depth"))],
    "null_v10_xyz_k10_max": max(null[("xyzibd", s, 10)]["v1.0"]["definite_pct"] for s in ("fp_raw", "depth")),
    "null_v11_cells_above5": sum(x > 5 for x in null_v11), "null_cells": len(null_v11),
    "seqnull_max": max(v["definite_pct"] for v in seqnull.values()),
    "wrong_any_v11": wrong_any, "replay_cells": len(rep), "seq_cells": len(seq),
    "v10_wrong_max_k3": max(v["v1.0"]["wrong"] for (p, d, s, k), v in rep.items() if k == 3),
    "full_unchanged": all(v["v1.0"] == v["v1.1"] for v in full.values()), "full_cells": len(full),
    "full_min_informative": min(v["images_with_pairs"] for v in full.values()),
    "n_scores": len(FPS) + len(WS),
    "replay_fp": {str(k): v for k, v in rfp.items()}, "replay_wapr": {str(k): v for k, v in rw.items()},
    "criteria": {
        "K1_null_le5_every_cell": all(x <= 5 for x in null_v11),
        "K2_fp_k10_classic_ge90": all(rep[(FPP, d, "fp_raw", 10)]["v1.1"]["correct"] >= 90 for d in CL),
        "K3_never_wrong": wrong_any == 0,
        "K4_seq10_fp_ge95_all_six": all(sq[d]["correct"] >= 95 for d in SIX),
        "K5_full_unchanged": all(v["v1.0"] == v["v1.1"] for v in full.values()),
    },
}
# ---------------- server 33-25-S: the released check on the public submission files ----------------
PUB = load("S25_PUBLIC.json")
assert PUB["rules"]["sha256"] == sha(os.path.join(D, "S25_PUBLIC_RULES.json")), "S25_PUBLIC.json was not run under S25_PUBLIC_RULES.json"
assert load("S25_PUBLIC_RULES.json")["tool"]["check_sha256"] == sha(os.path.join(D, "tool_check_v1_1.py")), "server used another check.py"
pf = PUB["files"]
cnt = lambda grp, r: sum(1 for f in pf if (grp is None or f["group"] == grp) and f["reading"] == r)
pend = [f for f in pf if f["reading"] is None]
pend_acc = [100.0 * (f["A1_pair_counts"][0] + 0.5 * f["A1_pair_counts"][1]) / f["A1_pair_counts"][2] for f in pend]
derived["public"] = {
    "files": len(pf), "rechecked": len(pf) - len(pend), "pending": len(pend),
    "reversed": cnt(None, "reversed"), "comparable": cnt(None, "comparable"), "no_information": cnt(None, "no_information"),
    "no_pairs": cnt(None, "no_pairs"), "too_few_images": cnt(None, "too_few_images"), "not_comparable": cnt(None, "not_comparable"),
    "control_comparable": cnt("control", "comparable"), "control_files": sum(1 for f in pf if f["group"] == "control"),
    "control_too_few": cnt("control", "too_few_images"),
    "control_too_few_images_with_pairs": sorted({f["images_with_pairs"] for f in pf if f["group"] == "control" and f["reading"] == "too_few_images"}),
    "pending_groups": sorted({f["group"] for f in pend}), "pending_min_accuracy_pp": min(pend_acc),
    "rechecked_accuracy_pp": [100.0 * min(f["accuracy"] for f in pf if f["reading"] in ("comparable", "too_few_images")),
                              100.0 * max(f["accuracy"] for f in pf if f["reading"] in ("comparable", "too_few_images"))],
    "min_images_comparable": min(f["images_with_pairs"] for f in pf if f["reading"] == "comparable"),
}
derived["inputs"].update({n: sha(os.path.join(D, n)) for n in ["S25_PUBLIC.json", "S25_PUBLIC_RULES.json", "REPORT33_25_S.md"]})
json.dump(derived, open(os.path.join(D, "derived_s25.json"), "w"), indent=1)
print("wrote tab_sign, supp_s25_{replay_fp,replay,null,seq}, derived_s25.json; criteria:", derived["criteria"])
